"""The judge validation report, `eval/judge_validation/report.md` (story V4, decision 006).

Every number comes from the committed answers file and the hand labels; the report names the
models that answered and how many cases each measure rests on.
"""

from collections.abc import Mapping, Sequence

from aiact.eval.judge import YES_AT, JudgeCheck
from aiact.eval.judge_validation import (
    Agreement,
    CalibrationBin,
    JudgeRecord,
    MarginRow,
    Route,
    Scored,
    ValidationCase,
    agreement,
    answered_records,
    backup_pairs,
    brier_score,
    calibration_bins,
    expected_calibration_error,
    in_check,
    in_language,
    jev_pairs,
    jev_points,
    judges_pairs,
    margin_rows,
    recommended_margin,
    scored_cases,
)
from aiact.schemas import Language

HEADER = """\
# Judge validation

Generated by `aiact evaluate judge-validation` from `answers.jsonl` and the hand labels in
`labels.yaml`; don't edit by hand. Decision 006 reads it. Jev's answer is yes when its
probability of yes is at least {yes_at}. A margin m sends a case to the backup judge when Jev's
probability lies strictly within m of {yes_at}, or when Jev failed.
"""


def format_report(
    cases: Sequence[ValidationCase],
    labels: Mapping[str, bool],
    records: Mapping[str, JudgeRecord],
    route: Route,
) -> str:
    scored = scored_cases(cases, labels, records, route)
    current = answered_records(cases, records, route)
    sections = [
        HEADER.format(yes_at=YES_AT),
        _summary(cases, labels, scored, current, route),
        _with_labels(scored),
        _between_judges(current),
        _calibration(scored),
        _margins(margin_rows(scored)),
        _disagreements(scored),
    ]
    return "\n".join(sections)


def _summary(
    cases: Sequence[ValidationCase],
    labels: Mapping[str, bool],
    scored: Sequence[Scored],
    current: Sequence[JudgeRecord],
    route: Route,
) -> str:
    by_language = ", ".join(
        f"{sum(c.language is language for c in cases)} {language.value.upper()}"
        for language in Language
    )
    yes = sum(labels.values())
    cost = sum(record.cost_usd for record in current)
    return (
        "## Summary\n\n"
        f"- Jev: `{route.jev_model}`; backup judge: `{route.backup_model}` on "
        f"`{route.backup_provider}`.\n"
        f"- Cases: {len(cases)} ({by_language}); labelled: {len(labels)} ({yes} yes, "
        f"{len(labels) - yes} no); answered by both judges: {len(current)}; measured "
        f"(labelled, with a current record): {len(scored)}.\n"
        f"- Cost of the answers counted here: ${cost:.4f}.\n"
    )


def _with_labels(scored: Sequence[Scored]) -> str:
    groups: list[tuple[str, Sequence[Scored]]] = [("all", scored)]
    groups += [(language.value.upper(), in_language(scored, language)) for language in Language]
    groups += [(check.value, in_check(scored, check)) for check in JudgeCheck]
    rows = [
        f"| {name} | {_agreement(agreement(jev_pairs(group)))} "
        f"| {_agreement(agreement(backup_pairs(group)))} |"
        for name, group in groups
    ]
    return (
        "## Agreement with the hand labels\n\n"
        "Agreed / cases (rate, Cohen's kappa); a judge that failed on a case leaves it out.\n\n"
        "| Cases | Jev | Backup judge |\n| --- | --- | --- |\n" + "\n".join(rows) + "\n"
    )


def _between_judges(current: Sequence[JudgeRecord]) -> str:
    return (
        "## Jev and the backup judge\n\n"
        "Over every case both answered, labelled or not: "
        f"{_agreement(agreement(judges_pairs(current)))}.\n"
    )


def _calibration(scored: Sequence[Scored]) -> str:
    points = jev_points(scored)
    bins = calibration_bins(points)
    brier, ece = brier_score(points), expected_calibration_error(bins)
    rows = "\n".join(_bin_row(item) for item in bins)
    return (
        "## Jev's calibration\n\n"
        f"Over {len(points)} labelled cases: Brier score {_number(brier)} (0 is perfect), "
        f"expected calibration error {_number(ece)}.\n\n"
        "| Probability of yes | Cases | Mean probability | Labelled yes |\n"
        "| --- | --- | --- | --- |\n" + rows + "\n"
    )


def _bin_row(item: CalibrationBin) -> str:
    closing = "]" if item.high == 1 else ")"
    return (
        f"| [{item.low:.1f}, {item.high:.1f}{closing} | {item.n} | {_number(item.mean_p)} "
        f"| {_number(item.yes_rate)} |"
    )


def _margins(rows: Sequence[MarginRow]) -> str:
    table = "\n".join(
        f"| {row.margin:.1f} | {row.sent_to_backup} | {_agreement(row.with_labels)} "
        f"| {row.unmeasured} |"
        for row in rows
    )
    best = recommended_margin(rows)
    choice = (
        f"Highest agreement at the smallest margin: **{best:.1f}**."
        if best is not None
        else "No labelled case has a record yet, so no margin can be recommended."
    )
    return (
        "## Unsure margin\n\n"
        "| Margin | Sent to the backup judge | Combined judge vs labels | Not measured |\n"
        "| --- | --- | --- | --- |\n" + table + "\n\n" + choice + "\n"
    )


def _disagreements(scored: Sequence[Scored]) -> str:
    rows = [
        f"| {s.case.id} | {s.case.check.value} | {_yes_no(s.label)} | {_number(s.record.p_yes)} "
        f"| {_yes_no(s.record.holds)} |"
        for s in scored
        if _jev_disagrees(s) or (s.record.holds is not None and s.record.holds != s.label)
    ]
    if not rows:
        return "## Cases a judge got wrong\n\nNone.\n"
    return (
        "## Cases a judge got wrong\n\n"
        "| Case | Check | Label | Jev's probability of yes | Backup judge |\n"
        "| --- | --- | --- | --- | --- |\n" + "\n".join(rows) + "\n"
    )


def _jev_disagrees(s: Scored) -> bool:
    return s.record.p_yes is not None and (s.record.p_yes >= YES_AT) != s.label


def _agreement(value: Agreement) -> str:
    if value.rate is None:
        return "no cases"
    kappa = "n/a" if value.kappa is None else f"{value.kappa:.2f}"
    return f"{value.agreed}/{value.n} ({value.rate:.0%}, κ {kappa})"


def _number(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.3f}"


def _yes_no(value: bool | None) -> str:
    return "n/a" if value is None else ("yes" if value else "no")
