"""Download the source documents into `data/raw/` and record them in `data/manifest.yaml`.

`aiact corpus fetch` walks the registry in `aiact.corpus.sources` one request at a time. The run
is idempotent: a document whose sha256 matches the manifest keeps its entry (and `fetched_at`)
unchanged, so a re-run with no upstream change leaves the manifest byte-for-byte identical.
Each entry has one of three states:
- `available: true`: downloaded; `file`, `bytes`, `sha256` and `fetched_at` describe it.
- `available: false`: confirmed not published (the registry says so, or the server returns 404),
  with an `absent_reason`. Later stories may skip it.
- `available: null`: the download failed (bot challenge, timeout, wrong content) and no earlier run
  has it, with a `fetch_error`. It is unknown, not absent, so later stories must not skip it.
A failed download never overwrites what an earlier run recorded; it is reported, the command exits
non-zero, and the run carries on with the next document.

HTML is checked for its language (the `<title>` names it). A PDF's language is taken on trust
from the registry; story C2 checks it once Docling has extracted the text.
"""

import hashlib
import logging
import re
import time
from collections.abc import Callable
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

import httpx
import yaml
from pydantic import BaseModel, ConfigDict

from aiact.corpus.files import write_atomic
from aiact.corpus.sources import SOURCES, DocStatus, Kind, Language, Source
from aiact.settings import DEFAULT_DATA_DIR

logger = logging.getLogger(__name__)

DEFAULT_MANIFEST = DEFAULT_DATA_DIR / "manifest.yaml"
"""The committed manifest in this checkout (raw files go to the shared data dir instead)."""

USER_AGENT = "aiact-corpus-fetch/0.1 (AI Act Classification Assistant; capstone research)"
TIMEOUT_SECONDS = 60.0
MAX_ATTEMPTS = 4
BACKOFF_SECONDS = 10.0
"""First retry wait; doubles on each further attempt."""
PAUSE_SECONDS = 3.0
"""Wait between two downloads: one request at a time, never a burst."""
RETRYABLE_STATUS = frozenset({202, 429, 500, 502, 503, 504})
"""202 is the AWS WAF challenge the EU sites answer bots with (empty body)."""
SNIFF_BYTES = 2048
TITLE_SCAN_BYTES = 65536
TITLE_RE = re.compile(rb"<title>([^<]*)</title>", re.IGNORECASE)
XHTML_ACCEPT = "application/xhtml+xml"
MANIFEST_HEADER = (
    "# Generated by `aiact corpus fetch`; do not edit by hand.\n"
    "# One entry per document and language. Raw files live in $AIACT_DATA_DIR/raw/<file>.\n"
    "# `status` is the document's legal status. `available: false` means no such language\n"
    "# version is published (see `absent_reason`); `available: null` means the download failed\n"
    "# and the state is unknown (see `fetch_error`).\n"
)


class ManifestEntry(BaseModel):
    """What the manifest records for one document in one language."""

    model_config = ConfigDict(frozen=True)

    id: str
    language: Language
    title: str
    kind: Kind
    status: DocStatus
    version: str
    source_page: str
    url: str | None
    accept_language: str | None = None
    celex: str | None = None
    """CELEX number of a law (for example `32026R1744` for the Omnibus); null for guidance."""
    available: bool | None
    """True: downloaded. False: confirmed not published. None: the download failed."""
    absent_reason: str | None = None
    fetch_error: str | None = None
    file: str | None = None
    bytes: int | None = None
    sha256: str | None = None
    fetched_at: str | None = None
    """UTC time the current content (this sha256) was first downloaded."""

    @property
    def key(self) -> tuple[str, Language]:
        return (self.id, self.language)


class Manifest(BaseModel):
    model_config = ConfigDict(frozen=True)

    documents: tuple[ManifestEntry, ...] = ()


class FetchError(Exception):
    """A download that failed for a reason other than the document not existing."""


class NotPublishedError(Exception):
    """The server says the document doesn't exist (HTTP 404)."""


@dataclass(frozen=True)
class FetchReport:
    manifest: Manifest
    changed: tuple[str, ...] = ()
    """`id.lang` of entries that are new or have new content."""
    failures: tuple[str, ...] = ()
    """`id.lang: reason` for downloads that failed this run."""
    manifest_written: bool = False


@dataclass(frozen=True)
class Fetcher:
    """Downloads one URL at a time, politely: a User-Agent, a timeout, a few retries."""

    client: httpx.Client
    sleep: Callable[[float], None] = time.sleep
    max_attempts: int = MAX_ATTEMPTS
    backoff: float = BACKOFF_SECONDS

    def get(self, url: str, accept_language: str | None = None) -> bytes:
        """Download `url`; `accept_language` asks Cellar for that language's XHTML."""
        headers = (
            {"Accept": XHTML_ACCEPT, "Accept-Language": accept_language} if accept_language else {}
        )
        last_problem = "no attempt made"
        for attempt in range(self.max_attempts):
            if attempt:
                self.sleep(self.backoff * 2 ** (attempt - 1))
            try:
                response = self.client.get(url, headers=headers)
            except httpx.TransportError as exc:
                last_problem = f"{type(exc).__name__}"
                logger.warning("fetch %s attempt %d: %s", url, attempt + 1, last_problem)
                continue
            except httpx.HTTPError as exc:  # too many redirects, undecodable body: not retried
                raise FetchError(type(exc).__name__) from exc
            if response.status_code == 404:
                raise NotPublishedError(url)
            if response.status_code in RETRYABLE_STATUS:
                last_problem = f"HTTP {response.status_code}"
                logger.warning("fetch %s attempt %d: %s", url, attempt + 1, last_problem)
                continue
            if response.status_code != 200:
                raise FetchError(f"HTTP {response.status_code}")
            return response.content
        raise FetchError(f"gave up after {self.max_attempts} attempts ({last_problem})")


def make_client(transport: httpx.BaseTransport | None = None) -> httpx.Client:
    return httpx.Client(
        headers={"User-Agent": USER_AGENT},
        timeout=TIMEOUT_SECONDS,
        follow_redirects=True,
        transport=transport,
    )


def check_content(content: bytes, kind: Kind, language: Language) -> None:
    """Reject a body that isn't the expected file type (an error or challenge page).

    For HTML, the `<title>` must also name the language (EUR-Lex titles read
    `L_202401689DE.000101.fmx.xml` or `Konsolidierter TEXT: 32024R1689 — DE — …`), so a
    server falling back to another language can't slip through as German.
    """
    head = content[:SNIFF_BYTES]
    is_valid = head.startswith(b"%PDF") if kind == "pdf" else b"<html" in head.lower()
    if not is_valid:
        raise FetchError(f"response is not {kind} ({len(content)} bytes)")
    if kind == "html":
        title = TITLE_RE.search(content[:TITLE_SCAN_BYTES])
        code = re.escape(language.upper().encode())
        if title is None or not re.search(rb"(?<![A-Z])" + code + rb"(?![A-Z])", title.group(1)):
            raise FetchError(f"html title doesn't name language {language}")


def sha256_of(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def load_manifest(path: Path) -> Manifest:
    """Read the manifest; a missing file is an empty manifest, a malformed one is an error."""
    if not path.exists():
        return Manifest()
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return Manifest.model_validate(data)


def dump_manifest(manifest: Manifest) -> str:
    data = manifest.model_dump(mode="json")
    return MANIFEST_HEADER + yaml.safe_dump(data, sort_keys=False, allow_unicode=True, width=100)


REGISTRY_FIELDS = frozenset(
    {"id", "language", "title", "kind", "status", "version"}
    | {"source_page", "url", "accept_language", "celex"}
)


def _registry_fields(source: Source) -> dict[str, object]:
    return source.model_dump(include=set(REGISTRY_FIELDS))


def _absent(source: Source, reason: str) -> ManifestEntry:
    return ManifestEntry.model_validate(
        _registry_fields(source) | {"available": False, "absent_reason": reason}
    )


def _failed(source: Source, reason: str) -> ManifestEntry:
    return ManifestEntry.model_validate(
        _registry_fields(source) | {"available": None, "fetch_error": reason}
    )


def _present(source: Source, content: bytes, fetched_at: str) -> ManifestEntry:
    return ManifestEntry.model_validate(
        _registry_fields(source)
        | {
            "available": True,
            "file": source.filename,
            "bytes": len(content),
            "sha256": sha256_of(content),
            "fetched_at": fetched_at,
        }
    )


def _write_raw(path: Path, content: bytes, sha256: str) -> None:
    """Write the raw file, unless it's already there with the same content."""
    if path.exists() and sha256_of(path.read_bytes()) == sha256:
        return
    write_atomic(path, content)


def utc_now() -> str:
    return datetime.now(UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")


@dataclass(frozen=True)
class _Outcome:
    entry: ManifestEntry
    is_changed: bool = False
    failure: str | None = None


def _fetch_one(
    source: Source,
    prior: ManifestEntry | None,
    fetcher: Fetcher,
    raw_dir: Path,
    now: Callable[[], str],
) -> _Outcome:
    if source.url is None:
        entry = _absent(source, source.absent_reason or "not published")
        return _Outcome(entry, is_changed=entry != prior)
    try:
        content = fetcher.get(source.url, source.accept_language)
        check_content(content, source.kind, source.language)
    except NotPublishedError:
        if prior is not None and prior.available:
            return _Outcome(prior, failure="HTTP 404, but an earlier run found it; entry kept")
        entry = _absent(source, f"Not published: the server returns HTTP 404 for {source.url}.")
        return _Outcome(entry, is_changed=entry != prior)
    except FetchError as exc:
        if prior is not None and prior.available is not None:
            return _Outcome(prior, failure=str(exc))
        entry = _failed(source, str(exc))
        return _Outcome(entry, is_changed=entry != prior, failure=str(exc))

    sha256 = sha256_of(content)
    _write_raw(raw_dir / source.filename, content, sha256)
    if prior is not None and prior.sha256 == sha256 and prior.fetched_at is not None:
        entry = _present(source, content, prior.fetched_at)
        return _Outcome(entry, is_changed=entry != prior)
    return _Outcome(_present(source, content, now()), is_changed=True)


def fetch_all(
    manifest_path: Path,
    raw_dir: Path,
    fetcher: Fetcher,
    sources: tuple[Source, ...] = SOURCES,
    now: Callable[[], str] = utc_now,
    pause: float = PAUSE_SECONDS,
) -> FetchReport:
    """Fetch every source, update the raw files and rewrite the manifest only if it changed."""
    old_text = manifest_path.read_text(encoding="utf-8") if manifest_path.exists() else None
    previous = {entry.key: entry for entry in load_manifest(manifest_path).documents}
    entries: list[ManifestEntry] = []
    changed: list[str] = []
    failures: list[str] = []
    for index, source in enumerate(sources):
        if index and source.url is not None:
            fetcher.sleep(pause)
        label = f"{source.id}.{source.language}"
        outcome = _fetch_one(
            source, previous.get((source.id, source.language)), fetcher, raw_dir, now
        )
        if outcome.failure is not None:
            logger.error("fetch %s failed: %s", label, outcome.failure)
            failures.append(f"{label}: {outcome.failure}")
        entries.append(outcome.entry)
        if outcome.is_changed:
            changed.append(label)

    manifest = Manifest(documents=tuple(entries))
    new_text = dump_manifest(manifest)
    is_written = new_text != old_text
    if is_written:
        write_atomic(manifest_path, new_text.encode("utf-8"))
    return FetchReport(manifest, tuple(changed), tuple(failures), is_written)
