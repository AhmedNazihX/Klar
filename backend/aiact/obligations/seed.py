"""The SQL seed for `public.obligations`, generated from the obligations YAML (`aiact obligations
seed`).

`supabase db reset` loads the SQL file (config.toml > [db.seed]); the YAML stays the one source.
"""

from pathlib import Path

from aiact.obligations.list import OBLIGATIONS_FILE, ObligationRow, ObligationTable

SEED_SQL_FILE = OBLIGATIONS_FILE.with_suffix(".sql")
"""The committed SQL seed, next to the YAML."""

COLUMNS = (
    "obligation_key",
    "position",
    "role",
    "risk_class",
    "high_risk_route",
    "duty",
    "article",
    "applies_from",
    "applies_if",
    "relief_note",
    "note",
    "law_version",
)


def _literal(value: object) -> str:
    """A SQL literal: null, a bare integer, or a single-quoted string with quotes doubled."""
    if value is None:
        return "null"
    if isinstance(value, int):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def _values(position: int, row: ObligationRow, table: ObligationTable) -> str:
    obligation = row.obligation
    values = (
        row.key,
        position,
        row.role.value,
        row.risk_class.value,
        obligation.high_risk_route.value if obligation.high_risk_route else None,
        obligation.duty,
        obligation.article,
        obligation.applies_from.isoformat(),
        obligation.applies_if,
        obligation.relief_note,
        obligation.note,
        table.law_version.value,
    )
    return "  (" + ", ".join(_literal(value) for value in values) + ")"


def render_seed_sql(table: ObligationTable) -> str:
    """The seed script: replaces this law version's rows, so running it twice changes nothing."""
    rows = table.rows()
    law_version = _literal(table.law_version.value)
    values = ",\n".join(_values(position, row, table) for position, row in enumerate(rows))
    return (
        "-- Generated by `aiact obligations seed` from supabase/seed/obligations.yaml; "
        "do not edit by hand.\n"
        f"-- {len(rows)} rows, law version {table.law_version.value}, "
        f"checked on {table.checked_on.isoformat()}.\n\n"
        f"delete from public.obligations where law_version = {law_version};\n\n"
        f"insert into public.obligations ({', '.join(COLUMNS)}) values\n{values};\n"
    )


def write_seed_sql(table: ObligationTable, path: Path = SEED_SQL_FILE) -> bool:
    """Write the seed; returns False when the file already holds exactly this content."""
    content = render_seed_sql(table)
    if path.exists() and path.read_text(encoding="utf-8") == content:
        return False
    path.write_text(content, encoding="utf-8")
    return True
